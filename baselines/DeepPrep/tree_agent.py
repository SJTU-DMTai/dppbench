"""Execution-grounded reasoning-tree inference for DeepPrep.

The model emits ``<plan>`` plus ``<expand>`` or ``<answer>``. Successful
operator executions materialize one tree node per operator; ``<execute>`` is
always generated by the environment and is never treated as a model action.
"""
