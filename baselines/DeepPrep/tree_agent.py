_PLAN_RE = re.compile(r"<plan>(.*?)</plan>", re.DOTALL)
_THINK_RE = re.compile(r"<think>(.*?)</think>", re.DOTALL)
_ACTIONS = {
    "expand": re.compile(r"<expand(?P<attrs>[^>]*)>(?P<body>.*?)</expand>", re.DOTALL),
    "answer": re.compile(r"<answer(?P<attrs>[^>]*)>(?P<body>.*?)</answer>", re.DOTALL),
    # Legacy tags remain parseable for older saved protocol traces. The
    # DeepPrep agent itself rejects these action kinds.
    "operator": re.compile(r"<operator(?P<attrs>[^>]*)>(?P<body>.*?)</operator>", re.DOTALL),
    "solution": re.compile(r"<solution(?P<attrs>[^>]*)>(?P<body>.*?)</solution>", re.DOTALL),
}
_PARENT_RE = re.compile(r"parent\s*=\s*(['\"])(.*?)\1", re.DOTALL)
_PARENT_BODY_RE = re.compile(r"<parent>(.*?)</parent>", re.DOTALL)
_PIPELINE_BODY_RE = re.compile(r"<pipeline>(.*?)</pipeline>", re.DOTALL)
_BACKTRACK_RE = re.compile(r"<backtrack\s*/?>")
_OP_CALL_RE = re.compile(r"^([A-Za-z_][A-Za-z_0-9]*)\s*(\((.*)\))?$", re.DOTALL)
_NATIVE_CALL = r"[A-Za-z_][A-Za-z_0-9]*\s*\((?:[^()]|\([^()]*\))*\)"
_NATIVE_EXECUTE_RE = re.compile(
    rf"(?ms)^[ \t]*(?P<chain>{_NATIVE_CALL}(?:\s*-->\s*{_NATIVE_CALL})*)"
    r"\s*</execute>"
)


@dataclass
class ParsedAction:
    kind: str
    chain_str: Optional[str] = None
    think: Optional[str] = None
    plan: Optional[str] = None
    parent_chain: Optional[str] = None


def _extract_reasoning(text: str, regex: re.Pattern) -> Optional[str]:
    match = regex.search(text)
    return match.group(1).strip() if match else None


def parse_response(text: str) -> ParsedAction:
    plan = _extract_reasoning(text, _PLAN_RE)
    think = _extract_reasoning(text, _THINK_RE)
    if not think and "</think>" in text:
        # Some Qwen chat-template combinations include the opening tag in the
        # prompt, so decoded new tokens contain only its closing tag.
        think = text.split("</think>", 1)[0].strip() or None
    # Released Qwen3 checkpoints may still emit their native thinking block
    # despite protocol instructions. Treat it as the plan for compatibility.
    if not plan and think:
        plan = think
    found = []
    # Tags quoted in reasoning/prose are not actions. Actual tagged actions
    # must start a line (or follow a complete reasoning block).
    action_text = re.sub(r"<(?:think|plan)>.*?</(?:think|plan)>", "", text, flags=re.DOTALL)
    if "</think>" in action_text:
        action_text = action_text.rsplit("</think>", 1)[-1]
    for kind, regex in _ACTIONS.items():
        for match in regex.finditer(action_text):
            prefix = action_text[action_text.rfind('\n', 0, match.start()) + 1:match.start()].strip()
            if prefix and not re.fullmatch(
                r"(?:<(?:expand|answer|operator|solution)[^>]*>.*?</(?:expand|answer|operator|solution)>\s*)+",
                prefix,
            ):
                continue
            attrs = match.group("attrs") or ""
            body = match.group("body").strip()
            parent_match = _PARENT_RE.search(attrs)
            parent_body = _PARENT_BODY_RE.search(body)
            pipeline_body = _PIPELINE_BODY_RE.search(body)
            found.append((
                kind,
                pipeline_body.group(1).strip() if pipeline_body else body,
                (
                    parent_body.group(1).strip()
                    if parent_body
                    else parent_match.group(2).strip() if parent_match else None
                ),
            ))
    if _BACKTRACK_RE.search(text):
        found.append(("backtrack", None, None))
    if not found:
        # The released checkpoint may emit its concrete chain directly and
        # terminate it with </execute>, without an opening action tag.
        native = _NATIVE_EXECUTE_RE.search(text)
        if native:
            found.append(("expand", native.group("chain").strip(), None))
            if not plan:
                start = text.rfind("<think>", 0, native.start())
                if start >= 0:
                    native_think = text[start + len("<think>"):native.start()].strip()
                    if native_think:
                        think = native_think
                        plan = native_think
    if len(found) != 1:
        return ParsedAction("noop", think=think, plan=plan)
    kind, body, parent = found[0]
    return ParsedAction(kind, chain_str=body, think=think, plan=plan, parent_chain=parent)


def _parse_arg_value(raw: str) -> Any:
    raw = raw.strip()
    try:
        return ast.literal_eval(raw)
    except Exception:
        try:
            return json.loads(raw)
        except Exception:
            return raw.strip("'\"")


def _split_args(value: str) -> list[str]:
    parts, buf = [], []
    depth = 0
    quote: Optional[str] = None
    for char in value:
        if quote:
            buf.append(char)
            if char == quote and (len(buf) < 2 or buf[-2] != "\\"):
                quote = None
        elif char in "'\"":
            quote = char
            buf.append(char)
        elif char in "([{":
            depth += 1
            buf.append(char)
        elif char in ")]}":
            depth -= 1
            buf.append(char)
        elif char == "," and depth == 0:
            parts.append("".join(buf).strip())
            buf = []
        else:
            buf.append(char)
    if buf:
        parts.append("".join(buf).strip())
    return [part for part in parts if part]


def _parse_op_call(call: str) -> tuple[str, dict]:
    match = _OP_CALL_RE.match(call.strip())
    if not match:
        raise ValueError(f"Could not parse operator call: {call!r}")
    params = {}
    for item in _split_args(match.group(3) or ""):
        if "=" not in item:
            params.setdefault("__positional__", []).append(_parse_arg_value(item))
            continue
        key, value = item.split("=", 1)
        params[key.strip()] = _parse_arg_value(value)
    return match.group(1), params


@dataclass
class ChainParseError(Exception):
    message: str

    def __str__(self) -> str:
        return self.message


def chain_to_steps(
    chain_str: str,
    ctx: DataContext,
    rng: random.Random,
    *,
    drop_terminate: bool = True,
    strict_instances: bool = False,
) -> list[PipelineStep]:
    """Parse a concrete operator chain.

    ``strict_instances=True`` is used by DeepPrep and never derives random or
    dataset-dependent parameters. The compatibility default retains the old
    common ``make_step`` behavior for baselines that import this helper.
    """
    valid_ops = {spec.op_name for spec in get_available_ops(ctx.task_type)}
    steps = []
    for raw in [part.strip() for part in chain_str.split("-->") if part.strip()]:
        try:
            op_name, supplied = _parse_op_call(raw)
            op_name, supplied = adapt_operator_instance(op_name, supplied)
        except ValueError as exc:
            raise ChainParseError(str(exc)) from exc
        if op_name == "Terminate":
            if not drop_terminate:
                steps.append(PipelineStep(op="Terminate", target="both", params={}))
            continue
        try:
            spec = get_op(op_name)
        except KeyError as exc:
            raise ChainParseError(f"Unknown operator {op_name!r}.") from exc
        if op_name not in valid_ops:
            raise ChainParseError(f"Operator {op_name!r} is unavailable for {ctx.task_type}.")
        if "__positional__" in supplied:
            raise ChainParseError(
                f"Operator {op_name!r} requires keyword arguments. "
                f"Accepted keywords: {sorted(get_operator_param_names(op_name) or [])}. "
                "Input tables are supplied by the environment; remove positional table arguments."
            )
        if strict_instances:
            params = copy.deepcopy(spec.default_params or {})
            params.update(supplied)
            target = default_target_for(op_name, ctx.task_type)
        else:
            base = make_step(op_name, ctx, rng)
            if base is None:
                raise ChainParseError(f"Operator {op_name!r} cannot be applied in this context.")
            params = dict(base.params or {})
            params.update(supplied)
            target = base.target
        errors = validate_step_params(op_name, params, ctx, strict=True)
        if errors:
            raise ChainParseError(
                "; ".join(errors)
                + f". {op_name} accepted keywords: {sorted(get_operator_param_names(op_name) or [])}; "
                + f"required: {list(spec.required_params)}; defaults: {spec.default_params}. "
                + "Do not pass df= or table=; the environment supplies the input. "
                + "Resubmit a corrected full path inside <expand>, with a brief <plan>."
            )
        steps.append(PipelineStep(op=op_name, target=target, params=params))
    if not steps:
        raise ChainParseError("An expansion must contain at least one operator.")
    return steps


@dataclass
class AgentRunResult:
    pipeline: Pipeline
    success: bool
    n_turns: int
    n_errors: int
    transcript: list[dict] = field(default_factory=list)
    tree: dict = field(default_factory=dict)
    solution_attempts: list[dict] = field(default_factory=list)  # compatibility


class TreeAgent:
    def __init__(
        self,
        llm: LLMClient,
        sandbox: Sandbox,
        ctx: DataContext,
        max_explore_turn: int = 5,
        max_chain_len: int = 6,
        max_depth: int = 8,
        max_err_cnt: int = 5,
        verbose: bool = True,
        seed: int = 42,
        downstream_evaluator=None,
        max_solution_attempts: int = 1,
    ) -> None:
        self.llm = llm
        self.sandbox = sandbox
        self.ctx = ctx
        self.target_schema = TargetSchema.from_context(ctx)
        self.max_explore_turn = int(max_explore_turn)
        self.max_chain_len = int(max_chain_len)
        self.max_depth = int(max_depth)
        self.max_err_cnt = int(max_err_cnt)
        self.verbose = bool(verbose)
        self._rng = random.Random(seed)
        self.tree = SearchTree()
        self.transcript = []
        self.n_errors = 0
        self._validated_pipelines: dict[str, Pipeline] = {}
        self.downstream_evaluator = downstream_evaluator
        self.candidate_scores: dict[str, dict] = {}

    def _auc_feedback(self, node: SearchNode) -> str:
        pipeline = self._pipeline_for_node(node)
        key = canonical_path(node.accumulated_steps)
        if key not in self.candidate_scores:
            auc, metrics, error = self.downstream_evaluator.evaluate_for_agent(pipeline)
            if auc is None or not math.isfinite(auc):
                error = error or 'No finite validation AUC returned'
            self.candidate_scores[key] = dict(path=key, auc=auc if not error else None,
                                              metrics=metrics, error=error)
        record = self.candidate_scores[key]
        valid = [r for r in self.candidate_scores.values() if r['auc'] is not None]
        best = max(valid, key=lambda r: r['auc']) if valid else None
        return (
            '\nSampled downstream feedback: ' + json.dumps(record, default=str)
            + '\nBest sampled validation AUC so far: ' + (str(best['auc']) if best else 'none')
            + '\nContinue exploring a different legal full path to improve validation AUC. '
            'Use training errors to revise operators; do not repeat the same path. '
            'Do not use test metrics or force extra operators merely to increase length.'
        )

    def _log(self, message: str) -> None:
        if self.verbose:
            print("[DeepPrep.Agent]", message)

    def _revision_hint(self) -> str:
        cursor = self.tree.cursor
        path = canonical_path(cursor.accumulated_steps)
        remaining = sorted(set(mandatory_ops_for_context(self.ctx)) - set(s.op for s in cursor.accumulated_steps))
        lines = [f"Current materialized path (copy exactly): {path}",
                 f"Mandatory operators still required: {remaining}. These are not optional.",
                 "Emit exact case-sensitive operator calls with keyword parameters, not an abstract uppercase chain."]
        if 'CreateSequence' in remaining:
            params = dict(user_col=self.ctx.user_col or 'user_id', item_col=self.ctx.item_col or 'item_id',
                          time_col=self.ctx.time_col or 'timestamp', seq_col='item_id_seq', max_len=50)
            example = canonical_path([PipelineStep('CreateSequence', 'interaction', params)])
            lines.append("CreateSequence syntax for this task: " + example)
            lines.append("Continuation syntax: " + (path + " --> " if path != 'root' else '') + example + " </execute>")
        if 'JoinTable' in remaining:
            lines.append("JoinTable remains mandatory; extra joined feature columns are expected, not a schema violation.")
        return '\n'.join(lines)

    def _initial_messages(self, observation: str) -> list[dict]:
        summary_lines = [
            f"task_type={self.ctx.task_type} dataset={self.ctx.data_name}",
            f"target_col={self.ctx.target_col} time_col={self.ctx.time_col} id_col={self.ctx.id_col}",
            f"user_col={self.ctx.user_col} item_col={self.ctx.item_col}",
            "source_tables:",
        ]
        for table_name in self.ctx.source_tables():
            table = self.ctx.tables.get(table_name)
            if table is None:
                continue
            summary_lines.append(
                f"- {table_name}: role={table.role} shape={table.shape} "
                f"dtypes={dict(list(table.dtypes.items())[:40])} "
                f"categorical_columns={[c for c, dtype in table.dtypes.items() if str(dtype) in ('object', 'string', 'category')]} "
                f"join_keys_to_primary={table.join_keys_to_primary}"
            )
        summary = "\n".join(summary_lines)
        mandatory_ops = mandatory_ops_for_context(self.ctx)
        required_ops_text = "\n".join(
            f"- {name}" for name in mandatory_ops
        ) or "- none"
        user = render_user_initial(
            task_type=self.ctx.task_type,
            data_name=self.ctx.data_name,
            summary_text=summary,
            required_ops_text=required_ops_text,
            target_schema_text=self.target_schema.render(),
            op_descriptions=format_op_descriptions(self.ctx.task_type),
            obs_text=observation,
            max_chain_len=self.max_chain_len,
            max_explore_turn=self.max_explore_turn,
        )
        return [{"role": "system", "content": SYSTEM_TREE_SEARCH}, {"role": "user", "content": user}]

    def _parent(self, path: Optional[str]) -> tuple[Optional[SearchNode], Optional[str]]:
        if path is None:
            return None, "The action must specify an exact parent path."
        if path.strip().lower() in ("", "root", "<root>"):
            node = self.tree.find_by_path("root")
        else:
            try:
                steps = chain_to_steps(
                    path, self.ctx, self._rng, strict_instances=True
                )
            except ChainParseError as exc:
                return None, f"Invalid parent path: {exc}"
            node = self.tree.find_by_steps(steps)
        if node is None:
            return None, f"Unknown materialized parent path: {path!r}."
        return node, None

    def _resolve_expansion(self, chain: str) -> tuple[SearchNode, list[PipelineStep]]:
        full_steps = chain_to_steps(
            chain, self.ctx, self._rng, strict_instances=True
        )
        for prefix_len in range(len(full_steps), -1, -1):
            parent = self.tree.find_by_steps(full_steps[:prefix_len])
            if parent is None:
                continue
            new_steps = full_steps[prefix_len:]
            if not new_steps:
                raise ChainParseError(
                    "Expansion repeats an existing path but appends no new operator."
                )
            return parent, new_steps
        raise ChainParseError("Expansion has no materialized root-to-node prefix.")

    def _pipeline_for_node(self, node: SearchNode) -> Pipeline:
        pipe = Pipeline(steps=copy.deepcopy(node.accumulated_steps))
        assign_dag_structure(pipe, self.ctx, self._rng)
        return pipe

    def _answer_errors(self, node: SearchNode) -> list[str]:
        obs = self.sandbox.restore(node.snapshot)  # type: ignore[arg-type]
        errors = self.target_schema.validate_observation(obs)
        if self.ctx.task_type == "tabular":
            remaining = [
                c for c, dtype in obs.dtypes.items()
                if str(dtype) in ("object", "string", "category")
                and c not in (self.ctx.target_col, "__split__")
            ]
            if remaining:
                errors.append(
                    f"Unencoded categorical features: {remaining}. "
                    "Use LabelEncode(cols=None) to select all categorical features automatically."
                )
        report = check_pipeline(self._pipeline_for_node(node), self.ctx)
        errors.extend(report.errors)
        return errors

    def _fallback_pipeline(self) -> Pipeline:
        scored = [r for r in self.candidate_scores.values() if r['auc'] is not None]
        if scored:
            best = max(scored, key=lambda r: r['auc'])
            return self._pipeline_for_node(self.tree.find_by_steps(
                chain_to_steps(best['path'], self.ctx, self._rng, strict_instances=True)))
        if self._validated_pipelines:
            return copy.deepcopy(max(self._validated_pipelines.values(), key=lambda p: len(p.steps)))
        candidates = sorted(self.tree.nodes.values(), key=lambda node: node.depth, reverse=True)
        for node in candidates:
            try:
                if not self._answer_errors(node):
                    return self._pipeline_for_node(node)
            except BudgetExceededError:
                break
        return self._pipeline_for_node(self.tree.nodes[self.tree.root_id])  # type: ignore[index]

    def run(self) -> AgentRunResult:
        reset = self.sandbox.reset()
        if not reset.success or reset.obs is None or reset.snapshot is None:
            return AgentRunResult(Pipeline(), False, 0, 1)
        self.tree.add_root(reset.snapshot, reset.obs.text)
        messages = self._initial_messages(reset.obs.text)
        if self.downstream_evaluator is not None:
            messages[0]['content'] += (
                '\nSearch objective: maximize sampled validation AUC under the shared budget. '
                'A legal pipeline is only a candidate, not an instruction to stop. '
                'Use AUC and training errors to compare and revise distinct legal paths. '
                'Do not repeatedly finalize the first candidate; explore alternative operators or parameters.'
            )
        final_pipeline = None
        turn = 0

        for turn in range(1, self.max_explore_turn + 1):
            try:
                response = self.llm.chat(messages)
            except BudgetExceededError as exc:
                self.transcript.append({"role": "environment", "content": str(exc), "turn": turn})
                break
            except Exception as exc:
                self.n_errors += 1
                self._log(f"LLM call failed: {exc}")
                if self.n_errors >= self.max_err_cnt:
                    break
                continue
            messages.append({"role": "assistant", "content": response})
            self.transcript.append({"role": "assistant", "content": response, "turn": turn})
            action = parse_response(response)
            turns_left = self.max_explore_turn - turn

            if action.kind not in ("expand", "answer"):
                self.n_errors += 1
                feedback = render_protocol_error(
                    "Missing concrete operator chain or a complete action tag.",
                    turns_left,
                )
                feedback += "\n" + self._revision_hint()
                messages.append({"role": "user", "content": feedback})
                self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
                if self.n_errors >= self.max_err_cnt:
                    break
                continue

            if action.kind == "answer":
                parent, parent_error = self._parent(
                    action.parent_chain or action.chain_str
                )
                if parent_error:
                    self.n_errors += 1
                    feedback = render_protocol_error(parent_error, turns_left)
                    messages.append({"role": "user", "content": feedback})
                    self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
                    continue
                assert parent is not None
                self.tree.set_cursor(parent.node_id)
                errors = self._answer_errors(parent)
                if not errors:
                    if self.downstream_evaluator is not None:
                        self._validated_pipelines[parent.node_id] = self._pipeline_for_node(parent)
                        feedback = self._auc_feedback(parent)
                        messages.append({'role': 'user', 'content': feedback})
                        self.transcript.append({'role': 'environment', 'content': feedback, 'turn': turn})
                        continue
                    parent.is_terminal = True
                    final_pipeline = self._pipeline_for_node(parent)
                    break
                self.n_errors += 1
                feedback = render_execute(
                    parent_path=canonical_path(parent.accumulated_steps),
                    executed_path="",
                    obs_text="",
                    error="Target schema or pipeline contract not satisfied: " + "; ".join(errors),
                    turn_left=turns_left,
                )
                messages.append({"role": "user", "content": feedback})
                self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
                continue

            try:
                # The released checkpoint often finalizes by repeating its
                # native chain rather than switching to <answer>. Accept only
                # an exact materialized path already validated in this run.
                existing, _ = self._parent(action.chain_str)
                if existing is not None and existing.node_id in self._validated_pipelines:
                    if self.downstream_evaluator is not None:
                        feedback = self._auc_feedback(existing)
                        messages.append({'role': 'user', 'content': feedback})
                        self.transcript.append({'role': 'environment', 'content': feedback, 'turn': turn})
                        continue
                    existing.is_terminal = True
                    final_pipeline = copy.deepcopy(self._validated_pipelines[existing.node_id])
                    self.transcript.append({
                        "role": "environment", "turn": turn,
                        "content": '<execute status="OK">Repeated validated path accepted as final answer.</execute>',
                    })
                    break
                if action.parent_chain is not None:
                    parent, parent_error = self._parent(action.parent_chain)
                    if parent_error:
                        raise ChainParseError(parent_error)
                    steps = chain_to_steps(
                        action.chain_str or "", self.ctx, self._rng,
                        strict_instances=True,
                    )
                else:
                    parent, steps = self._resolve_expansion(action.chain_str or "")
                assert parent is not None
                if len(steps) > self.max_chain_len:
                    raise ChainParseError(
                        f"Expansion has {len(steps)} operators; limit is {self.max_chain_len}."
                    )
                if parent.depth + len(steps) > self.max_depth:
                    raise ChainParseError(f"Expansion exceeds max tree depth {self.max_depth}.")
            except ChainParseError as exc:
                self.n_errors += 1
                feedback = render_execute(
                    parent_path="unchanged",
                    executed_path="",
                    obs_text="",
                    error=f"Operator parse/validation failed: {exc}",
                    turn_left=turns_left,
                )
                feedback += "\n" + self._revision_hint()
                messages.append({"role": "user", "content": feedback})
                self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
                continue

            self.tree.set_cursor(parent.node_id)
            self.sandbox.restore(parent.snapshot)  # type: ignore[arg-type]

            result = None
            failure = None
            for step in steps:
                result = self.sandbox.execute_chain([step])
                if not result.success:
                    failure = result.error or "unknown execution failure"
                    self.tree.mark_cursor_error(failure)
                    break
                self.tree.add_child([step], result.snapshot, result.obs.text)  # type: ignore[arg-type,union-attr]

            cursor = self.tree.cursor
            if not failure:
                try:
                    candidate_errors = self._answer_errors(cursor)
                    if not candidate_errors:
                        self._validated_pipelines[cursor.node_id] = self._pipeline_for_node(cursor)
                except BudgetExceededError as exc:
                    self.transcript.append({"role": "environment", "content": str(exc), "turn": turn})
                    break
            feedback = render_execute(
                parent_path=canonical_path(parent.accumulated_steps),
                executed_path=canonical_path(cursor.accumulated_steps),
                obs_text=result.obs.text if result and result.success and result.obs else "",
                error=failure,
                turn_left=turns_left,
                remaining_required_ops=sorted(
                    set(mandatory_ops_for_context(self.ctx))
                    - {
                        step.op for step in cursor.accumulated_steps
                    }
                ),
            )
            if failure:
                self.n_errors += 1
            elif candidate_errors:
                feedback += "\nCandidate contract errors: " + "; ".join(candidate_errors)
            else:
                if self.downstream_evaluator is not None:
                    feedback += self._auc_feedback(cursor)
                else:
                    feedback += "\nCandidate validated. Finish with <answer>" + canonical_path(cursor.accumulated_steps) + "</answer>."
            if failure or candidate_errors:
                feedback += "\n" + self._revision_hint()
            messages.append({"role": "user", "content": feedback})
            self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
            if self.n_errors >= self.max_err_cnt:
                break

        success = final_pipeline is not None
        if final_pipeline is None:
            final_pipeline = self._fallback_pipeline()
        if self.downstream_evaluator is not None:
            success = any(r['auc'] is not None for r in self.candidate_scores.values())
        return AgentRunResult(
            pipeline=final_pipeline,
            success=success,
            n_turns=turn,
            n_errors=self.n_errors,
            transcript=self.transcript,
            tree=self.tree.to_dict(),
            solution_attempts=list(self.candidate_scores.values()),
        )


