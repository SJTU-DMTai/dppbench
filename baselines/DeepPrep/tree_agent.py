_PLAN_RE = re.compile(r"<plan>(.*?)</plan>", re.DOTALL)
_THINK_RE = re.compile(r"<think>(.*?)</think>", re.DOTALL)
_ACTIONS = {
    "expand": re.compile(r"<expand(?P<attrs>[^>]*)>(?P<body>.*?)</expand>", re.DOTALL),
    "answer": re.compile(r"<answer(?P<attrs>[^>]*)>(?P<body>.*?)</answer>", re.DOTALL),
    # Legacy tags remain parseable for older saved protocol traces. The
    # DeepPrep agent itself rejects these action kinds.
    "operator": re.compile(r"<operator(?P<attrs>[^>]*)>(?P<body>.*?)</operator>", re.DOTALL),
    "solution": re.compile(r"<solution(?P<attrs>[^>]*)>(?P<body>.*?)</solution>", re.DOTALL),
}
_PARENT_RE = re.compile(r"parent\s*=\s*(['\"])(.*?)\1", re.DOTALL)
_PARENT_BODY_RE = re.compile(r"<parent>(.*?)</parent>", re.DOTALL)
_PIPELINE_BODY_RE = re.compile(r"<pipeline>(.*?)</pipeline>", re.DOTALL)
_BACKTRACK_RE = re.compile(r"<backtrack\s*/?>")
_OP_CALL_RE = re.compile(r"^([A-Za-z_][A-Za-z_0-9]*)\s*(\((.*)\))?$", re.DOTALL)
_NATIVE_CALL = r"[A-Za-z_][A-Za-z_0-9]*\s*\((?:[^()]|\([^()]*\))*\)"
_NATIVE_EXECUTE_RE = re.compile(
    rf"(?ms)^[ \t]*(?P<chain>{_NATIVE_CALL}(?:\s*-->\s*{_NATIVE_CALL})*)"
    r"\s*</execute>"
)


@dataclass
class ParsedAction:
    kind: str
    chain_str: Optional[str] = None
    think: Optional[str] = None
    plan: Optional[str] = None
    parent_chain: Optional[str] = None
    error: Optional[str] = None


def _extract_reasoning(text: str, regex: re.Pattern) -> Optional[str]:
    match = regex.search(text)
    return match.group(1).strip() if match else None


def parse_response(text: str, *, strict_native: bool = False) -> ParsedAction:
    plan = _extract_reasoning(text, _PLAN_RE)
    think = _extract_reasoning(text, _THINK_RE)
    if not think and "</think>" in text:
        # Some Qwen chat-template combinations include the opening tag in the
        # prompt, so decoded new tokens contain only its closing tag.
        think = text.split("</think>", 1)[0].strip() or None
    # Released Qwen3 checkpoints may still emit their native thinking block
    # despite protocol instructions. Treat it as the plan for compatibility.
    if not plan and think:
        plan = think
    found = []
    # Tags quoted in reasoning/prose are not actions. Actual tagged actions
    # must start a line (or follow a complete reasoning block).
    action_text = re.sub(r"<(?:think|plan)>.*?</(?:think|plan)>", "", text, flags=re.DOTALL)
    if "</think>" in action_text:
        action_text = action_text.rsplit("</think>", 1)[-1]
    for kind, regex in _ACTIONS.items():
        for match in regex.finditer(action_text):
            prefix = action_text[action_text.rfind('\n', 0, match.start()) + 1:match.start()].strip()
            if prefix and not re.fullmatch(
                r"(?:<(?:expand|answer|operator|solution)[^>]*>.*?</(?:expand|answer|operator|solution)>\s*)+",
                prefix,
            ):
                continue
            if strict_native and action_text[:match.start()].rstrip().endswith("-->"):
                return ParsedAction("noop", think=think, plan=plan,
                                    error="Dangling prefix before tagged action. No operator was executed; resubmit the entire chain.")
            attrs = match.group("attrs") or ""
            body = match.group("body").strip()
            parent_match = _PARENT_RE.search(attrs)
            parent_body = _PARENT_BODY_RE.search(body)
            pipeline_body = _PIPELINE_BODY_RE.search(body)
            found.append((
                kind,
                pipeline_body.group(1).strip() if pipeline_body else body,
                (
                    parent_body.group(1).strip()
                    if parent_body
                    else parent_match.group(2).strip() if parent_match else None
                ),
            ))
    if _BACKTRACK_RE.search(text):
        found.append(("backtrack", None, None))
    if not found:
        # The released checkpoint may emit its concrete chain directly and
        # terminate it with </execute>, without an opening action tag.
        native = _NATIVE_EXECUTE_RE.search(text)
        if native and strict_native:
            matches = list(_NATIVE_EXECUTE_RE.finditer(text))
            prefix_lines = text[:native.start()].rstrip().splitlines()
            previous = prefix_lines[-1].strip() if prefix_lines else ""
            if len(matches) != 1 or previous.endswith("-->"):
                return ParsedAction("noop", think=think, plan=plan,
                    error="Ambiguous or incomplete action chain: dangling prefix " + repr(previous) +
                          ". No operator was executed. Resubmit the entire chain with concrete calls; no prefix may be silently discarded.")
        if native:
            found.append(("expand", native.group("chain").strip(), None))
            if not plan:
                start = text.rfind("<think>", 0, native.start())
                if start >= 0:
                    native_think = text[start + len("<think>"):native.start()].strip()
                    if native_think:
                        think = native_think
                        plan = native_think
    if len(found) != 1:
        return ParsedAction("noop", think=think, plan=plan)
    kind, body, parent = found[0]
    if strict_native:
        kind = {"solution": "answer", "operator": "expand"}.get(kind, kind)
    return ParsedAction(kind, chain_str=body, think=think, plan=plan, parent_chain=parent)


def _parse_arg_value(raw: str) -> Any:
    raw = raw.strip()
    try:
        return ast.literal_eval(raw)
    except Exception:
        try:
            return json.loads(raw)
        except Exception:
            return raw.strip("'\"")


def _split_args(value: str) -> list[str]:
    parts, buf = [], []
    depth = 0
    quote: Optional[str] = None
    for char in value:
        if quote:
            buf.append(char)
            if char == quote and (len(buf) < 2 or buf[-2] != "\\"):
                quote = None
        elif char in "'\"":
            quote = char
            buf.append(char)
        elif char in "([{":
            depth += 1
            buf.append(char)
        elif char in ")]}":
            depth -= 1
            buf.append(char)
        elif char == "," and depth == 0:
            parts.append("".join(buf).strip())
            buf = []
        else:
            buf.append(char)
    if buf:
        parts.append("".join(buf).strip())
    return [part for part in parts if part]


def _parse_op_call(call: str) -> tuple[str, dict]:
    match = _OP_CALL_RE.match(call.strip())
    if not match:
        raise ValueError(f"Could not parse operator call: {call!r}")
    params = {}
    for item in _split_args(match.group(3) or ""):
        if "=" not in item:
            params.setdefault("__positional__", []).append(_parse_arg_value(item))
            continue
        key, value = item.split("=", 1)
        params[key.strip()] = _parse_arg_value(value)
    return match.group(1), params


@dataclass
class ChainParseError(Exception):
    message: str

    def __str__(self) -> str:
        return self.message


def chain_to_steps(
    chain_str: str,
    ctx: DataContext,
    rng: random.Random,
    *,
    drop_terminate: bool = True,
    strict_instances: bool = False,
    validate_rec_lookup: bool = False,
) -> list[PipelineStep]:
    """Parse a concrete operator chain.

    ``strict_instances=True, validate_rec_lookup=True`` is used by DeepPrep and never derives random or
    dataset-dependent parameters. The compatibility default retains the old
    common ``make_step`` behavior for baselines that import this helper.
    """
    valid_ops = {spec.op_name for spec in get_available_ops(ctx.task_type)}
    if strict_instances and any(not part.strip() for part in chain_str.split('-->')):
        raise ChainParseError('Incomplete chain: every arrow must connect two concrete operator calls')
    steps = []
    for raw in [part.strip() for part in chain_str.split("-->") if part.strip()]:
        try:
            op_name, supplied = _parse_op_call(raw)
            op_name, supplied = adapt_operator_instance(op_name, supplied)
        except ValueError as exc:
            raise ChainParseError(str(exc)) from exc
        if op_name == "Terminate":
            if not drop_terminate:
                steps.append(PipelineStep(op="Terminate", target="both", params={}))
            continue
        try:
            spec = get_op(op_name)
        except KeyError as exc:
            raise ChainParseError(f"Unknown operator {op_name!r}.") from exc
        if op_name not in valid_ops:
            raise ChainParseError(f"Operator {op_name!r} is unavailable for {ctx.task_type}.")
        if "__positional__" in supplied and validate_rec_lookup:
            # DeepPrep-only diagnostics; shared callers keep the old contract.
            values = supplied["__positional__"]
            prose = any(isinstance(v, str) and v.strip().lower().startswith(("to ", "for ", "用于", "为了")) for v in values)
            category = "natural-language explanation inside parentheses" if prose else "positional arguments"
            raise ChainParseError(
                f"Rejected call: {raw!r}. Found {category}: {values!r}. "
                f"Operator {op_name!r} requires keyword arguments. "
                f"Accepted keywords: {sorted(get_operator_param_names(op_name) or [])}. "
                "Descriptions are not executable arguments. Choose concrete key=value parameters "
                "from the catalog; do not put a purpose statement in parentheses. "
                "The environment supplies the input table. No call was executed or rewritten."
            )
        if "__positional__" in supplied:
            raise ChainParseError(
                f"Operator {op_name!r} requires keyword arguments. "
                f"Accepted keywords: {sorted(get_operator_param_names(op_name) or [])}. "
                "Input tables are supplied by the environment; remove positional table arguments."
            )
        if strict_instances:
            params = copy.deepcopy(spec.default_params or {})
            params.update(supplied)
            target = default_target_for(op_name, ctx.task_type)
        else:
            base = make_step(op_name, ctx, rng)
            if base is None:
                raise ChainParseError(f"Operator {op_name!r} cannot be applied in this context.")
            params = dict(base.params or {})
            params.update(supplied)
            target = base.target
        errors = validate_step_params(op_name, params, ctx, strict=True)
        if strict_instances:
            from .candidate_contracts import parameter_errors
            errors.extend(parameter_errors(op_name, params, ctx))
        if validate_rec_lookup:
            errors.extend(lookup_reference_errors(op_name, params, ctx))
        if errors:
            raise ChainParseError(
                "; ".join(errors)
                + f". {op_name} accepted keywords: {sorted(get_operator_param_names(op_name) or [])}; "
                + f"required: {list(spec.required_params)}; defaults: {spec.default_params}. "
                + (f" Rejected call: {raw!r}. Correct the reported parameter; use only catalog keywords. "
                   "Return the corrected full path on one line ending in </execute>; no <plan> block."
                   if validate_rec_lookup else
                   "Do not pass df= or table=; the environment supplies the input. "
                   "Resubmit a corrected full path inside <expand>, with a brief <plan>.")
            )
        steps.append(PipelineStep(op=op_name, target=target, params=params))
    if not steps:
        raise ChainParseError("An expansion must contain at least one operator.")
    return steps


@dataclass
class AgentRunResult:
    pipeline: Pipeline
    success: bool
    n_turns: int
    n_errors: int
    transcript: list[dict] = field(default_factory=list)
    tree: dict = field(default_factory=dict)
    solution_attempts: list[dict] = field(default_factory=list)  # compatibility
    stop_reason: str = "unknown"


class TreeAgent:
    def __init__(
        self,
        llm: LLMClient,
        sandbox: Sandbox,
        ctx: DataContext,
        max_explore_turn: int = 5,
        max_chain_len: int = 6,
        max_depth: int = 8,
        max_err_cnt: int = 5,
        verbose: bool = True,
        seed: int = 42,
        downstream_evaluator=None,
        max_solution_attempts: int = 1,
        max_repeated_paths: int = 2,
        model_config=None,
    ) -> None:
        self.model_config = model_config or {}
        self.llm = llm
        self.sandbox = sandbox
        self.ctx = ctx
        self.target_schema = TargetSchema.from_context(ctx)
        self.max_explore_turn = int(max_explore_turn)
        self.max_chain_len = int(max_chain_len)
        self.max_depth = int(max_depth)
        self.max_err_cnt = int(max_err_cnt)
        self.max_repeated_paths = int(max_repeated_paths)
        if self.max_repeated_paths < 2:
            raise ValueError("max_repeated_paths must be >= 2 (one warning before stopping)")
        self.stop_reason = "round_limit"
        self._repeat_path = None
        self._repeat_count = 0
        self.verbose = bool(verbose)
        self._rng = random.Random(seed)
        self.tree = SearchTree()
        self.transcript = []
        self.n_errors = 0
        self._validated_pipelines: dict[str, Pipeline] = {}
        self._validation_errors: dict[str, list[str]] = {}
        self._failed_expansions: dict[str, str] = {}
        self.downstream_evaluator = downstream_evaluator
        self.candidate_scores: dict[str, dict] = {}
        self.search_stats = {"response_attempts": 0, "response_parse_failures": 0,
                             "llm_call_attempts": 0, "llm_call_failures": 0,
                             "execution_failure_cache_hits": 0,
                             "expansion_validation_failures": 0, "score_requests": 0, "cache_hits": 0,
                             "unique_candidates_scored": 0, "successful_candidates": 0,
                             "repeated_paths": 0}

    def _downstream_feedback(self, node: SearchNode) -> str:
        pipeline = self._pipeline_for_node(node)
        key = canonical_path(node.accumulated_steps)
        self.search_stats["score_requests"] += 1
        cached = key in self.candidate_scores
        if cached:
            self.search_stats["cache_hits"] += 1
        if key not in self.candidate_scores:
            from .model_contract import sequence_input_errors
            errors = sequence_input_errors(pipeline, self.ctx, self.model_config)
            if errors:
                fitness, metrics, error = None, {}, "; ".join(errors)
            else:
                fitness, metrics, error = self.downstream_evaluator.evaluate_for_agent(pipeline)
            if error:
                raise_if_resource_error(error)
            if fitness is None or not math.isfinite(fitness):
                error = error or 'No finite validation fitness (higher is better) returned'
            self.candidate_scores[key] = dict(path=key, fitness=fitness if not error else None,
                                              metric_name=getattr(self.downstream_evaluator, 'metric_key', None),
                                              metrics=metrics, error=error, evaluated=not bool(errors))
        record = self.candidate_scores[key]
        # Keep protocol manifests in the artifact, not in the model feedback.
        feedback_record = {k: record[k] for k in ("path", "fitness", "metric_name", "error")}
        feedback_record["cache_hit"] = cached
        self.search_stats["unique_candidates_checked"] = len(self.candidate_scores)
        self.search_stats["model_contract_failures"] = sum(not r.get('evaluated', True) for r in self.candidate_scores.values())
        self.search_stats["unique_candidates_scored"] = sum(r.get('evaluated', True) for r in self.candidate_scores.values())
        self.search_stats["successful_candidates"] = sum(r['fitness'] is not None for r in self.candidate_scores.values())
        valid = [r for r in self.candidate_scores.values() if r['fitness'] is not None]
        best = max(valid, key=lambda r: r['fitness']) if valid else None
        return (
            '\nSampled downstream feedback: ' + json.dumps(feedback_record, default=str)
            + '\nBest sampled validation fitness (higher is better) so far: ' + (str(best['fitness']) if best else 'none')
            + ('\nThis path was successfully scored. You may submit this exact path with <answer>, or explore a different legal path.'
               if record['fitness'] is not None else
               '\nThis path FAILED scoring and cannot be submitted as a successful answer. Correct the reported error in the full path; appending unrelated operators does not fix it.')
            + ' Do not use test metrics or force extra operators merely to increase length.'
        )

    def _log(self, message: str) -> None:
        if self.verbose:
            print("[DeepPrep.Agent]", message)

    def _record_feedback(self, feedback: str, turn: int) -> None:
        """Persist full feedback and expose failures in the experiment log."""
        self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
        # Do not dump data observations or prompts into the main log.
        for marker in ("error: ", "Candidate contract errors: "):
            if marker in feedback:
                message = feedback.split(marker, 1)[1].split("</execute>", 1)[0]
                self._log(f"turn={turn} {marker}{message[:2000]}")
                break

    def _revision_hint(self) -> str:
        cursor = self.tree.cursor
        path = canonical_path(cursor.accumulated_steps)
        remaining = sorted(set(mandatory_ops_for_context(self.ctx)) - set(s.op for s in cursor.accumulated_steps))
        lines = [f"Current materialized path (copy exactly): {path}",
                 f"Mandatory operators still required: {remaining}. These are not optional.",
                 "Use exact names; do not lowercase them. Use keyword arguments, never explanatory prose inside parentheses.",
                 "Correct only the reported problem. Reply with at most one explanatory sentence and a concrete full chain ending in </execute>."]
        examples = []
        if 'CreateSequence' in remaining:
            params = dict(user_col=self.ctx.user_col or 'user_id', item_col=self.ctx.item_col or 'item_id',
                          time_col=self.ctx.time_col or 'timestamp', seq_col='item_id_seq', max_len=50)
            example = canonical_path([PipelineStep('CreateSequence', 'interaction', params)])
            lines.append("CreateSequence syntax for this task: " + example)
            examples.append(example)
        if 'JoinTable' in remaining:
            if self.ctx.task_type != 'rec':
                for name, table in self.ctx.tables.items():
                    if name == self.ctx.primary_table:
                        continue
                    for keys in table.join_keys_to_primary:
                        key = keys['secondary']
                        if key != keys['primary']:
                            continue
                        method = 'key' if table.join_key_unique.get(key, False) else 'agg'
                        params = dict(method=method, aux_df='$' + name + '_df', key_col=key, how='left')
                        if method == 'agg':
                            params.update(prefix=name + '__', agg_funcs=['mean', 'min', 'max'])
                        lines.append('Available relationship (right key ' +
                                     ('unique' if method == 'key' else 'repeated; aggregate before joining') + '): ' +
                                     canonical_path([PipelineStep('JoinTable', self.ctx.primary_table, params)]))
            if self.ctx.task_type == 'rec':
                params = dict(method='rec', user_col=self.ctx.user_col or 'user_id',
                              item_col=self.ctx.item_col or 'item_id', how='left')
                for table in ('user', 'item'):
                    if table in self.ctx.secondary_tables:
                        params[table + '_df'] = '$' + table + '_df'
                example = canonical_path([PipelineStep('JoinTable', 'interaction', params)])
                lines.append("JoinTable syntax for this task: " + example)
                examples.append(example)
            lines.append("JoinTable needs two input table branches, not two preceding operators. Extra joined columns are expected.")
        if examples:
            # One illustrative extension, not an automatically completed solution.
            lines.append("Continuation syntax: " + (path + " --> " if path != 'root' else '') + examples[0] + " </execute>")
            lines.append("This illustrates syntax only; retain all mandatory operators in your chosen final path.")
        return '\n'.join(lines)

    def _initial_messages(self, observation: str) -> list[dict]:
        summary_lines = [
            f"task_type={self.ctx.task_type} dataset={self.ctx.data_name}",
            f"target_col={self.ctx.target_col} time_col={self.ctx.time_col} id_col={self.ctx.id_col}",
            f"user_col={self.ctx.user_col} item_col={self.ctx.item_col}",
            "source_tables:",
        ]
        for table_name in self.ctx.source_tables():
            table = self.ctx.tables.get(table_name)
            if table is None:
                continue
            summary_lines.append(
                f"- {table_name}: role={table.role} shape={table.shape} "
                f"dtypes={dict(list(table.dtypes.items())[:40])} "
                f"categorical_columns={[c for c, dtype in table.dtypes.items() if str(dtype) in ('object', 'string', 'category')]} "
                f"join_keys_to_primary={table.join_keys_to_primary} "
                f"right_key_unique={table.join_key_unique}"
            )
        summary = "\n".join(summary_lines)
        mandatory_ops = mandatory_ops_for_context(self.ctx)
        required_ops_text = "\n".join(
            f"- {name}" for name in mandatory_ops
        ) or "- none"
        user = render_user_initial(
            task_type=self.ctx.task_type,
            data_name=self.ctx.data_name,
            summary_text=summary,
            required_ops_text=required_ops_text,
            target_schema_text=self.target_schema.render(),
            op_descriptions=format_op_descriptions(self.ctx.task_type),
            obs_text=observation,
            max_chain_len=self.max_chain_len,
            max_explore_turn=self.max_explore_turn,
            model_contract_text=str({"model": self.model_config.get("model"), "sequence_mappings": self.model_config.get("feature", {}).get("seq_cols", {})}),
        )
        return [{"role": "system", "content": SYSTEM_TREE_SEARCH}, {"role": "user", "content": user}]

    def _parent(self, path: Optional[str]) -> tuple[Optional[SearchNode], Optional[str]]:
        if path is None:
            return None, "The action must specify an exact parent path."
        if path.strip().lower() in ("", "root", "<root>"):
            node = self.tree.find_by_path("root")
        else:
            try:
                steps = chain_to_steps(
                    path, self.ctx, self._rng, strict_instances=True, validate_rec_lookup=True
                )
            except ChainParseError as exc:
                return None, f"Invalid parent path: {exc}"
            node = self.tree.find_by_steps(steps)
        if node is None:
            return None, f"Unknown materialized parent path: {path!r}."
        return node, None

    def _resolve_expansion(self, chain: str) -> tuple[SearchNode, list[PipelineStep]]:
        full_steps = chain_to_steps(
            chain, self.ctx, self._rng, strict_instances=True, validate_rec_lookup=True
        )
        for prefix_len in range(len(full_steps), -1, -1):
            parent = self.tree.find_by_steps(full_steps[:prefix_len])
            if parent is None:
                continue
            new_steps = full_steps[prefix_len:]
            if not new_steps:
                raise ChainParseError(
                    "Expansion repeats an existing path but appends no new operator."
                )
            return parent, new_steps
        raise ChainParseError("Expansion has no materialized root-to-node prefix.")

    def _pipeline_for_node(self, node: SearchNode) -> Pipeline:
        pipe = Pipeline(steps=copy.deepcopy(node.accumulated_steps))
        assign_dag_structure(pipe, self.ctx, self._rng)
        return pipe

    def _answer_errors(self, node: SearchNode) -> list[str]:
        if node.node_id in self._validation_errors:
            return list(self._validation_errors[node.node_id])
        obs = self.sandbox.restore(node.snapshot)  # type: ignore[arg-type]
        errors = self.target_schema.validate_observation(obs)
        if self.ctx.task_type == "tabular":
            remaining = [
                c for c, dtype in obs.dtypes.items()
                if str(dtype) in ("object", "string", "category")
                and c not in (self.ctx.target_col, "__split__")
            ]
            if remaining:
                errors.append(
                    f"Unencoded categorical features: {remaining}. "
                    "Use LabelEncode(cols=None) to select all categorical features automatically."
                )
        report = check_deepprep_pipeline(self._pipeline_for_node(node), self.ctx)
        errors.extend(report.errors)
        self._validation_errors[node.node_id] = list(errors)
        return errors

    def _fallback_pipeline(self) -> Pipeline:
        scored = [r for r in self.candidate_scores.values() if r['fitness'] is not None]
        if scored:
            best = max(scored, key=lambda r: r['fitness'])
            return self._pipeline_for_node(self.tree.find_by_steps(
                chain_to_steps(best['path'], self.ctx, self._rng, strict_instances=True, validate_rec_lookup=True)))
        if self._validated_pipelines:
            return copy.deepcopy(max(self._validated_pipelines.values(), key=lambda p: len(p.steps)))
        candidates = sorted(self.tree.nodes.values(), key=lambda node: node.depth, reverse=True)
        for node in candidates:
            try:
                if not self._answer_errors(node):
                    return self._pipeline_for_node(node)
            except BudgetExceededError:
                break
        return self._pipeline_for_node(self.tree.nodes[self.tree.root_id])  # type: ignore[index]

    def run(self) -> AgentRunResult:
        try:
            return self._run_search()
        except BudgetExceededError as exc:
            self.stop_reason = "budget_exhausted"
            self.search_stats["stop_reason"] = self.stop_reason
            # Evaluating or executing the next candidate must not discard a
            # previously scored pipeline when the shared budget expires.
            if not self.tree.nodes:
                raise
            turns = max((item.get('turn', 0) for item in self.transcript), default=0)
            self.transcript.append({'role': 'environment', 'content': str(exc), 'turn': turns})
            fallback = self._fallback_pipeline()
            count = self.search_stats["successful_candidates"]
            self.search_stats["candidate_coverage"] = "none" if count == 0 else "single_candidate" if count == 1 else "multiple_candidates"
            self.search_stats["selected_path"] = canonical_path(fallback.steps)
            return AgentRunResult(
                pipeline=fallback,
                success=any(r['fitness'] is not None for r in self.candidate_scores.values()),
                stop_reason=self.stop_reason,
                n_turns=turns, n_errors=self.n_errors, transcript=self.transcript,
                tree=self.tree.to_dict(), solution_attempts=list(self.candidate_scores.values()),
            )

    def _run_search(self) -> AgentRunResult:
        reset = self.sandbox.reset()
        if not reset.success or reset.obs is None or reset.snapshot is None:
            self.stop_reason = "initialization_failed"
            self.search_stats["stop_reason"] = self.stop_reason
            return AgentRunResult(Pipeline(), False, 0, 1, stop_reason=self.stop_reason)
        self.tree.add_root(reset.snapshot, reset.obs.text)
        messages = self._initial_messages(reset.obs.text)
        if self.downstream_evaluator is not None:
            messages[0]['content'] += (
                '\nDPPBench adaptation: use sampled validation feedback to assess candidates. '
                'You may finish with <answer>PATH</answer> or <solution>PATH</solution> once the path is legal and successfully scored. '
                'Unused turns are a limit, not a requirement. No minimum number of operators or candidates is required. '
                'Alternatively propose a different full path; repeating an execution is not a new candidate.'
            )
        final_pipeline = None
        turn = 0

        for turn in range(1, self.max_explore_turn + 1):
            try:
                self.search_stats['llm_call_attempts'] += 1
                response = self.llm.chat(messages)
            except BudgetExceededError as exc:
                self.stop_reason = "budget_exhausted"
                self.transcript.append({"role": "environment", "content": str(exc), "turn": turn})
                break
            except LocalModelInitializationError as exc:
                self.search_stats['llm_call_failures'] += 1
                self.transcript.append({'role': 'environment', 'turn': turn,
                                        'stage': 'llm_initialization',
                                        'error_type': type(exc).__name__, 'content': str(exc)})
                raise
            except Exception as exc:
                self.search_stats['llm_call_failures'] += 1
                self.transcript.append({'role': 'environment', 'turn': turn,
                                        'stage': 'llm_generation', 'error_type': type(exc).__name__,
                                        'content': str(exc)})
                raise_if_resource_error(exc)
                self.n_errors += 1
                self._log(f"LLM call failed: {exc}")
                if self.n_errors >= self.max_err_cnt:
                    break
                continue
            generation = getattr(self.llm, "last_generation", None)
            generation = generation if isinstance(generation, dict) else None
            messages.append({"role": "assistant", "content": response})
            self.transcript.append({"role": "assistant", "content": response, "turn": turn,
                                    "generation": generation})
            self.search_stats["response_attempts"] += 1
            action = parse_response(response, strict_native=True)
            turns_left = self.max_explore_turn - turn

            if action.kind not in ("expand", "answer"):
                self._repeat_path = None
                self._repeat_count = 0
                self.search_stats["response_parse_failures"] += 1
                self.n_errors += 1
                feedback = render_protocol_error(
                    (action.error or "Missing concrete operator chain or a complete action tag.") + " "
                    + str({"parsed_kind": action.kind,
                           "generation": generation,
                           "expand_open": response.count("<expand"), "expand_close": response.count("</expand>"),
                           "answer_open": response.count("<answer"), "answer_close": response.count("</answer>")}),
                    turns_left,
                )
                feedback += "\n" + self._revision_hint()
                messages.append({"role": "user", "content": feedback})
                self._record_feedback(feedback, turn)
                if self.n_errors >= self.max_err_cnt:
                    break
                continue

            if action.kind == "answer":
                parent, parent_error = self._parent(
                    action.parent_chain or action.chain_str
                )
                if parent_error:
                    self.n_errors += 1
                    feedback = render_protocol_error(parent_error, turns_left)
                    messages.append({"role": "user", "content": feedback})
                    self._record_feedback(feedback, turn)
                    continue
                assert parent is not None
                self.tree.set_cursor(parent.node_id)
                errors = self._answer_errors(parent)
                if not errors:
                    if self.downstream_evaluator is not None:
                        self._validated_pipelines[parent.node_id] = self._pipeline_for_node(parent)
                        feedback = self._downstream_feedback(parent)
                        messages.append({'role': 'user', 'content': feedback})
                        self._record_feedback(feedback, turn)
                        record = self.candidate_scores[canonical_path(parent.accumulated_steps)]
                        if record['fitness'] is None:
                            self.n_errors += 1
                            continue
                    self.stop_reason = "model_answer"
                    self.search_stats['submitted_path'] = canonical_path(parent.accumulated_steps)
                    parent.is_terminal = True
                    final_pipeline = self._pipeline_for_node(parent)
                    break
                self.n_errors += 1
                feedback = render_execute(
                    parent_path=canonical_path(parent.accumulated_steps),
                    executed_path="",
                    obs_text="",
                    error="Target schema or pipeline contract not satisfied: " + "; ".join(errors),
                    turn_left=turns_left,
                )
                messages.append({"role": "user", "content": feedback})
                self._record_feedback(feedback, turn)
                continue

            try:
                # The released checkpoint often finalizes by repeating its
                # native chain rather than switching to <answer>. Accept only
                # an exact materialized path already validated in this run.
                existing, _ = self._parent(action.chain_str)
                if existing is not None and existing.node_id in self._validated_pipelines:
                    if self.downstream_evaluator is not None:
                        feedback = self._downstream_feedback(existing)
                        key = canonical_path(existing.accumulated_steps)
                        self._repeat_count = self._repeat_count + 1 if key == self._repeat_path else 1
                        self._repeat_path = key
                        self.search_stats['repeated_paths'] += 1
                        if self._repeat_count >= self.max_repeated_paths:
                            self.stop_reason = "repeat_stagnation"
                            self._record_feedback("Repeated execution limit reached; returning the best successfully scored candidate if available.", turn)
                            break
                        feedback += ("\nRepeated execution: no new candidate was scored. " +
                                     (("Submit <answer>" + key + "</answer> to finish, or send a different complete path. ")
                                      if self.candidate_scores[key]["fitness"] is not None else
                                      "This path failed scoring; fix the reported error. It cannot be submitted as a successful answer. ") +
                                     f"Repeating this path {self.max_repeated_paths} consecutive times stops as repeat_stagnation, not model_answer.")
                        messages.append({'role': 'user', 'content': feedback})
                        self._record_feedback(feedback, turn)
                        continue
                    self.stop_reason = "validated_native_repeat"
                    existing.is_terminal = True
                    final_pipeline = copy.deepcopy(self._validated_pipelines[existing.node_id])
                    self.transcript.append({
                        "role": "environment", "turn": turn,
                        "content": '<execute status="OK">Repeated validated path accepted as final answer.</execute>',
                    })
                    break
                self._repeat_path = None
                self._repeat_count = 0
                if action.parent_chain is not None:
                    parent, parent_error = self._parent(action.parent_chain)
                    if parent_error:
                        raise ChainParseError(parent_error)
                    steps = chain_to_steps(
                        action.chain_str or "", self.ctx, self._rng,
                        strict_instances=True, validate_rec_lookup=True,
                    )
                else:
                    parent, steps = self._resolve_expansion(action.chain_str or "")
                assert parent is not None
                if len(steps) > self.max_chain_len:
                    raise ChainParseError(
                        f"Expansion has {len(steps)} operators; limit is {self.max_chain_len}."
                    )
                if parent.depth + len(steps) > self.max_depth:
                    raise ChainParseError(f"Expansion exceeds max tree depth {self.max_depth}.")
            except ChainParseError as exc:
                self.search_stats["expansion_validation_failures"] += 1
                self.n_errors += 1
                feedback = render_execute(
                    parent_path="unchanged",
                    executed_path="",
                    obs_text="",
                    error=f"Operator parse/validation failed: {exc}",
                    turn_left=turns_left,
                )
                feedback += "\n" + self._revision_hint()
                messages.append({"role": "user", "content": feedback})
                self._record_feedback(feedback, turn)
                continue

            expansion_key = canonical_path(parent.accumulated_steps + steps)
            if expansion_key in self._failed_expansions:
                self.search_stats['execution_failure_cache_hits'] += 1
                self.n_errors += 1
                feedback = ('This exact expansion already failed execution (cached): ' +
                            self._failed_expansions[expansion_key] + '\n' + self._revision_hint())
                messages.append({'role': 'user', 'content': feedback})
                self._record_feedback(feedback, turn)
                if self.n_errors >= self.max_err_cnt:
                    break
                continue
            self.tree.set_cursor(parent.node_id)
            self.sandbox.restore(parent.snapshot)  # type: ignore[arg-type]

            result = None
            failure = None
            for step in steps:
                result = self.sandbox.execute_chain([step])
                if not result.success:
                    failure = result.error or "unknown execution failure"
                    raise_if_resource_error(failure)
                    self._failed_expansions[expansion_key] = failure
                    self.tree.mark_cursor_error(failure)
                    break
                self.tree.add_child([step], result.snapshot, result.obs.text)  # type: ignore[arg-type,union-attr]

            cursor = self.tree.cursor
            if not failure:
                try:
                    candidate_errors = self._answer_errors(cursor)
                    if not candidate_errors:
                        self._validated_pipelines[cursor.node_id] = self._pipeline_for_node(cursor)
                except BudgetExceededError as exc:
                    self.stop_reason = "budget_exhausted"
                    self.transcript.append({"role": "environment", "content": str(exc), "turn": turn})
                    break
            feedback = render_execute(
                parent_path=canonical_path(parent.accumulated_steps),
                executed_path=canonical_path(cursor.accumulated_steps),
                obs_text=result.obs.text if result and result.success and result.obs else "",
                error=failure,
                turn_left=turns_left,
                remaining_required_ops=sorted(
                    set(mandatory_ops_for_context(self.ctx))
                    - {
                        step.op for step in cursor.accumulated_steps
                    }
                ),
            )
            if failure:
                self.n_errors += 1
            elif candidate_errors:
                feedback += "\nCandidate contract errors: " + "; ".join(candidate_errors)
            else:
                if self.downstream_evaluator is not None:
                    feedback += self._downstream_feedback(cursor)
                else:
                    feedback += "\nCandidate validated. Finish with <answer>" + canonical_path(cursor.accumulated_steps) + "</answer>."
            if failure or candidate_errors:
                feedback += "\n" + self._revision_hint()
            messages.append({"role": "user", "content": feedback})
            self._record_feedback(feedback, turn)
            if self.n_errors >= self.max_err_cnt:
                break

        # A later unscored answer must not replace the best successful candidate.
        if self.downstream_evaluator is not None and any(r['fitness'] is not None for r in self.candidate_scores.values()):
            final_pipeline = self._fallback_pipeline()
        success = final_pipeline is not None
        if final_pipeline is None:
            final_pipeline = self._fallback_pipeline()
        if self.downstream_evaluator is not None:
            success = any(r['fitness'] is not None for r in self.candidate_scores.values())
        if self.stop_reason == "round_limit" and self.n_errors >= self.max_err_cnt:
            self.stop_reason = "error_limit"
        self.search_stats["stop_reason"] = self.stop_reason
        count = self.search_stats["successful_candidates"]
        self.search_stats["candidate_coverage"] = "none" if count == 0 else "single_candidate" if count == 1 else "multiple_candidates"
        self.search_stats["selected_path"] = canonical_path(final_pipeline.steps)
        return AgentRunResult(
            stop_reason=self.stop_reason,
            pipeline=final_pipeline,
            success=success,
            n_turns=turn,
            n_errors=self.n_errors,
            transcript=self.transcript,
            tree=self.tree.to_dict(),
            solution_attempts=list(self.candidate_scores.values()),
        )


