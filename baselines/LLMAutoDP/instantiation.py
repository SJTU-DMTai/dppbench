"""LLM chooses operator order; the unchanged benchmark factory supplies params."""
import random
from baselines.common.pipeline import Pipeline, make_step, assign_dag_structure
from baselines.common.utils import get_available_ops


def instantiate_candidate(candidate, ctx, seed, max_len):
    if not isinstance(candidate, dict) or set(candidate) != {'operators'}:
        raise ValueError('Provide only {"operators": ["HandleMV", ...]}; parameters and DAG edges are generated by the benchmark')
    names = candidate['operators']
    if not isinstance(names, list) or not names or any(not isinstance(n, str) for n in names):
        raise ValueError('operators must be a nonempty list of operator names')
    if len(names) > max_len:
        raise ValueError('max_pipeline_len exceeded')
    allowed = {spec.op_name for spec in get_available_ops(ctx.task_type)}
    rng = random.Random(seed)  # Repeating a strategy repeats its instantiated candidate.
    steps = []
    for name in names:
        if name not in allowed:
            raise ValueError(f'Operator outside the task whitelist: {name}')
        step = make_step(name, ctx, rng)
        if step is None:
            raise ValueError(f'No applicable public parameter configuration for {name}')
        steps.append(step)
    pipeline = Pipeline(steps=steps)
    assign_dag_structure(pipeline, ctx, rng)
    return pipeline
