logger = logging.getLogger(__name__)

_PLAN_RE = re.compile(r"<plan>(.*?)</plan>", re.DOTALL)
_THINK_RE = re.compile(r"<think>(.*?)</think>", re.DOTALL)
_ACTIONS = {
    "expand": re.compile(r"<expand(?P<attrs>[^>]*)>(?P<body>.*?)</expand>", re.DOTALL),
    "answer": re.compile(r"<answer(?P<attrs>[^>]*)>(?P<body>.*?)</answer>", re.DOTALL),
    # Legacy tags remain parseable for DataMaster/ReAct compatibility. The
    # DeepPrep agent itself rejects these action kinds.
    "operator": re.compile(r"<operator(?P<attrs>[^>]*)>(?P<body>.*?)</operator>", re.DOTALL),
    "solution": re.compile(r"<solution(?P<attrs>[^>]*)>(?P<body>.*?)</solution>", re.DOTALL),
}
_PARENT_RE = re.compile(r"parent\s*=\s*(['\"])(.*?)\1", re.DOTALL)
_PARENT_BODY_RE = re.compile(r"<parent>(.*?)</parent>", re.DOTALL)
_PIPELINE_BODY_RE = re.compile(r"<pipeline>(.*?)</pipeline>", re.DOTALL)
_BACKTRACK_RE = re.compile(r"<backtrack\s*/?>")
_OP_CALL_RE = re.compile(r"^([A-Za-z_][A-Za-z_0-9]*)\s*(\((.*)\))?$", re.DOTALL)


@dataclass
class ParsedAction:
    kind: str
    chain_str: Optional[str] = None
    think: Optional[str] = None
    plan: Optional[str] = None
    parent_chain: Optional[str] = None


def _extract_reasoning(text: str, regex: re.Pattern) -> Optional[str]:
    match = regex.search(text)
    return match.group(1).strip() if match else None


def parse_response(text: str) -> ParsedAction:
    plan = _extract_reasoning(text, _PLAN_RE)
    think = _extract_reasoning(text, _THINK_RE)
    found = []
    for kind, regex in _ACTIONS.items():
        match = regex.search(text)
        if match:
            attrs = match.group("attrs") or ""
            body = match.group("body").strip()
            parent_match = _PARENT_RE.search(attrs)
            parent_body = _PARENT_BODY_RE.search(body)
            pipeline_body = _PIPELINE_BODY_RE.search(body)
            found.append((
                kind,
                pipeline_body.group(1).strip() if pipeline_body else body,
                (
                    parent_body.group(1).strip()
                    if parent_body
                    else parent_match.group(2).strip() if parent_match else None
                ),
            ))
    if _BACKTRACK_RE.search(text):
        found.append(("backtrack", None, None))
    if len(found) != 1:
        return ParsedAction("noop", think=think, plan=plan)
    kind, body, parent = found[0]
    return ParsedAction(kind, chain_str=body, think=think, plan=plan, parent_chain=parent)


def _parse_arg_value(raw: str) -> Any:
    raw = raw.strip()
    try:
        return ast.literal_eval(raw)
    except Exception:
        try:
            return json.loads(raw)
        except Exception:
            return raw.strip("'\"")


def _split_args(value: str) -> list[str]:
    parts, buf = [], []
    depth = 0
    quote: Optional[str] = None
    for char in value:
        if quote:
            buf.append(char)
            if char == quote and (len(buf) < 2 or buf[-2] != "\\"):
                quote = None
        elif char in "'\"":
            quote = char
            buf.append(char)
        elif char in "([{":
            depth += 1
            buf.append(char)
        elif char in ")]}":
            depth -= 1
            buf.append(char)
        elif char == "," and depth == 0:
            parts.append("".join(buf).strip())
            buf = []
        else:
            buf.append(char)
    if buf:
        parts.append("".join(buf).strip())
    return [part for part in parts if part]


def _parse_op_call(call: str) -> tuple[str, dict]:
    match = _OP_CALL_RE.match(call.strip())
    if not match:
        raise ValueError(f"Could not parse operator call: {call!r}")
    params = {}
    for item in _split_args(match.group(3) or ""):
        if "=" not in item:
            params.setdefault("__positional__", []).append(_parse_arg_value(item))
            continue
        key, value = item.split("=", 1)
        params[key.strip()] = _parse_arg_value(value)
    return match.group(1), params


@dataclass
class ChainParseError(Exception):
    message: str

    def __str__(self) -> str:
        return self.message


def chain_to_steps(
    chain_str: str,
    ctx: DataContext,
    rng: random.Random,
    *,
    drop_terminate: bool = True,
    strict_instances: bool = False,
) -> list[PipelineStep]:
    """Parse a concrete operator chain.

    ``strict_instances=True`` is used by DeepPrep and never derives random or
    dataset-dependent parameters. The compatibility default retains the old
    common ``make_step`` behavior for baselines that import this helper.
    """
    valid_ops = {spec.op_name for spec in get_available_ops(ctx.task_type)}
    steps = []
    for raw in [part.strip() for part in chain_str.split("-->") if part.strip()]:
        try:
            op_name, supplied = _parse_op_call(raw)
            op_name, supplied = adapt_operator_instance(op_name, supplied)
        except ValueError as exc:
            raise ChainParseError(str(exc)) from exc
        if op_name == "Terminate":
            if not drop_terminate:
                steps.append(PipelineStep(op="Terminate", target="both", params={}))
            continue
        try:
            spec = get_op(op_name)
        except KeyError as exc:
            raise ChainParseError(f"Unknown operator {op_name!r}.") from exc
        if op_name not in valid_ops:
            raise ChainParseError(f"Operator {op_name!r} is unavailable for {ctx.task_type}.")
        if "__positional__" in supplied:
            raise ChainParseError(f"Operator {op_name!r} requires keyword arguments.")
        if strict_instances:
            params = copy.deepcopy(spec.default_params or {})
            params.update(supplied)
            target = default_target_for(op_name, ctx.task_type)
        else:
            base = make_step(op_name, ctx, rng)
            if base is None:
                raise ChainParseError(f"Operator {op_name!r} cannot be applied in this context.")
            params = dict(base.params or {})
            params.update(supplied)
            target = base.target
        errors = validate_step_params(op_name, params, ctx, strict=True)
        if errors:
            raise ChainParseError("; ".join(errors))
        steps.append(PipelineStep(op=op_name, target=target, params=params))
    if not steps:
        raise ChainParseError("An expansion must contain at least one operator.")
    return steps


@dataclass
class AgentRunResult:
    pipeline: Pipeline
    success: bool
    n_turns: int
    n_errors: int
    transcript: list[dict] = field(default_factory=list)
    tree: dict = field(default_factory=dict)
    solution_attempts: list[dict] = field(default_factory=list)  # compatibility


class TreeAgent:
    def __init__(
        self,
        llm: LLMClient,
        sandbox: Sandbox,
        ctx: DataContext,
        max_explore_turn: int = 5,
        max_chain_len: int = 6,
        max_depth: int = 8,
        max_err_cnt: int = 5,
        verbose: bool = True,
        seed: int = 42,
        downstream_evaluator=None,
        max_solution_attempts: int = 1,
    ) -> None:
        self.llm = llm
        self.sandbox = sandbox
        self.ctx = ctx
        self.target_schema = TargetSchema.from_context(ctx)
        self.max_explore_turn = int(max_explore_turn)
        self.max_chain_len = int(max_chain_len)
        self.max_depth = int(max_depth)
        self.max_err_cnt = int(max_err_cnt)
        self.verbose = bool(verbose)
        self._rng = random.Random(seed)
        self.tree = SearchTree()
        self.transcript = []
        self.n_errors = 0
        if downstream_evaluator is not None:
            logger.warning("DeepPrep ignores downstream_evaluator during official-style inference")

    def _log(self, message: str) -> None:
        if self.verbose:
            print("[DeepPrep.Agent]", message)

    def _initial_messages(self, observation: str) -> list[dict]:
        summary = (
            f"task_type={self.ctx.task_type} dataset={self.ctx.data_name}\n"
            f"target_col={self.ctx.target_col} time_col={self.ctx.time_col} id_col={self.ctx.id_col}\n"
            f"source_tables={self.ctx.source_tables()}"
        )
        user = render_user_initial(
            task_type=self.ctx.task_type,
            data_name=self.ctx.data_name,
            summary_text=summary,
            target_schema_text=self.target_schema.render(),
            op_descriptions=format_op_descriptions(self.ctx.task_type),
            obs_text=observation,
            max_chain_len=self.max_chain_len,
            max_explore_turn=self.max_explore_turn,
        )
        return [{"role": "system", "content": SYSTEM_TREE_SEARCH}, {"role": "user", "content": user}]

    def _parent(self, path: Optional[str]) -> tuple[Optional[SearchNode], Optional[str]]:
        if path is None:
            return None, "The action must specify an exact parent path."
        if path.strip().lower() in ("", "root", "<root>"):
            node = self.tree.find_by_path("root")
        else:
            try:
                steps = chain_to_steps(
                    path, self.ctx, self._rng, strict_instances=True
                )
            except ChainParseError as exc:
                return None, f"Invalid parent path: {exc}"
            node = self.tree.find_by_steps(steps)
        if node is None:
            return None, f"Unknown materialized parent path: {path!r}."
        return node, None

    def _resolve_expansion(self, chain: str) -> tuple[SearchNode, list[PipelineStep]]:
        full_steps = chain_to_steps(
            chain, self.ctx, self._rng, strict_instances=True
        )
        for prefix_len in range(len(full_steps), -1, -1):
            parent = self.tree.find_by_steps(full_steps[:prefix_len])
            if parent is None:
                continue
            new_steps = full_steps[prefix_len:]
            if not new_steps:
                raise ChainParseError(
                    "Expansion repeats an existing path but appends no new operator."
                )
            return parent, new_steps
        raise ChainParseError("Expansion has no materialized root-to-node prefix.")

    def _pipeline_for_node(self, node: SearchNode) -> Pipeline:
        pipe = Pipeline(steps=copy.deepcopy(node.accumulated_steps))
        assign_dag_structure(pipe, self.ctx, self._rng)
        return pipe

    def _answer_errors(self, node: SearchNode) -> list[str]:
        obs = self.sandbox.restore(node.snapshot)  # type: ignore[arg-type]
        errors = self.target_schema.validate_observation(obs)
        report = check_pipeline(self._pipeline_for_node(node), self.ctx)
        errors.extend(report.errors)
        return errors

    def _fallback_pipeline(self) -> Pipeline:
        candidates = sorted(self.tree.nodes.values(), key=lambda node: node.depth, reverse=True)
        for node in candidates:
            if not self._answer_errors(node):
                return self._pipeline_for_node(node)
        return self._pipeline_for_node(self.tree.nodes[self.tree.root_id])  # type: ignore[index]

    def run(self) -> AgentRunResult:
        reset = self.sandbox.reset()
        if not reset.success or reset.obs is None or reset.snapshot is None:
            return AgentRunResult(Pipeline(), False, 0, 1)
        self.tree.add_root(reset.snapshot, reset.obs.text)
        messages = self._initial_messages(reset.obs.text)
        final_pipeline = None
        turn = 0

        for turn in range(1, self.max_explore_turn + 1):
            try:
                response = self.llm.chat(messages)
            except Exception as exc:
                self.n_errors += 1
                self._log(f"LLM call failed: {exc}")
                if self.n_errors >= self.max_err_cnt:
                    break
                continue
            messages.append({"role": "assistant", "content": response})
            self.transcript.append({"role": "assistant", "content": response, "turn": turn})
            action = parse_response(response)
            turns_left = self.max_explore_turn - turn

            if action.kind not in ("expand", "answer") or not action.plan:
                self.n_errors += 1
                feedback = render_protocol_error(
                    "Expected <plan> followed by exactly one <expand> or <answer>.",
                    turns_left,
                )
                messages.append({"role": "user", "content": feedback})
                self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
                if self.n_errors >= self.max_err_cnt:
                    break
                continue

            if action.kind == "answer":
                parent, parent_error = self._parent(
                    action.parent_chain or action.chain_str
                )
                if parent_error:
                    self.n_errors += 1
                    feedback = render_protocol_error(parent_error, turns_left)
                    messages.append({"role": "user", "content": feedback})
                    self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
                    continue
                assert parent is not None
                self.tree.set_cursor(parent.node_id)
                errors = self._answer_errors(parent)
                if not errors:
                    parent.is_terminal = True
                    final_pipeline = self._pipeline_for_node(parent)
                    break
                self.n_errors += 1
                feedback = render_execute(
                    parent_path=canonical_path(parent.accumulated_steps),
                    executed_path="",
                    obs_text="",
                    error="Target schema or pipeline contract not satisfied: " + "; ".join(errors),
                    turn_left=turns_left,
                )
                messages.append({"role": "user", "content": feedback})
                self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
                continue

            try:
                if action.parent_chain is not None:
                    parent, parent_error = self._parent(action.parent_chain)
                    if parent_error:
                        raise ChainParseError(parent_error)
                    steps = chain_to_steps(
                        action.chain_str or "", self.ctx, self._rng,
                        strict_instances=True,
                    )
                else:
                    parent, steps = self._resolve_expansion(action.chain_str or "")
                assert parent is not None
                if len(steps) > self.max_chain_len:
                    raise ChainParseError(
                        f"Expansion has {len(steps)} operators; limit is {self.max_chain_len}."
                    )
                if parent.depth + len(steps) > self.max_depth:
                    raise ChainParseError(f"Expansion exceeds max tree depth {self.max_depth}.")
            except ChainParseError as exc:
                self.n_errors += 1
                feedback = render_execute(
                    parent_path="unchanged",
                    executed_path="",
                    obs_text="",
                    error=f"Operator parse/validation failed: {exc}",
                    turn_left=turns_left,
                )
                messages.append({"role": "user", "content": feedback})
                self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
                continue

            self.tree.set_cursor(parent.node_id)
            self.sandbox.restore(parent.snapshot)  # type: ignore[arg-type]

            result = None
            failure = None
            for step in steps:
                result = self.sandbox.execute_chain([step])
                if not result.success:
                    failure = result.error or "unknown execution failure"
                    self.tree.mark_cursor_error(failure)
                    break
                self.tree.add_child([step], result.snapshot, result.obs.text)  # type: ignore[arg-type,union-attr]

            cursor = self.tree.cursor
            feedback = render_execute(
                parent_path=canonical_path(parent.accumulated_steps),
                executed_path=canonical_path(cursor.accumulated_steps),
                obs_text=result.obs.text if result and result.success and result.obs else "",
                error=failure,
                turn_left=turns_left,
            )
            if failure:
                self.n_errors += 1
            messages.append({"role": "user", "content": feedback})
            self.transcript.append({"role": "environment", "content": feedback, "turn": turn})
            if self.n_errors >= self.max_err_cnt:
                break

        success = final_pipeline is not None
        if final_pipeline is None:
            final_pipeline = self._fallback_pipeline()
        return AgentRunResult(
            pipeline=final_pipeline,
            success=success,
            n_turns=turn,
            n_errors=self.n_errors,
            transcript=self.transcript,
            tree=self.tree.to_dict(),
        )


